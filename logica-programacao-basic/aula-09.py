# Operadores aritméticos

print(f"Adição: 10 + 102 = {10 + 102}")
print(f"Subtração: 25 - 3 = {25 - 3}")
print(f"Multiplicação: 9 * 3 = {9 * 3}")
print(f"Divisão: 10 / 2 = {10 / 2}")
print(f"Divisão inteira: 25 // 5 = {25 // 5}")
print(f"Exponenciação: 2 ** 10 = {2 ** 10}")
print(f"Módulo: 25 % 5 = {25 % 5}") # Resto da Divisão
print(f"10 é par: {10 % 2 == 0} - (10 % 2 == 0)")
